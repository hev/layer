#!/usr/bin/env bash
# Writes the per-cluster Helm values (Workload Identity client ids, storage
# account) from this Terraform root's outputs. Nothing secret.
#   scripts/helm-values.sh > /tmp/layer-azure.values.yaml
set -euo pipefail
cd "$(dirname "$0")/.."

out=$(terraform output -json)
python3 - "$out" <<'PY'
import json, sys
o = {k: v["value"] for k, v in json.loads(sys.argv[1]).items()}
ids = o["workload_identity_client_ids"]
print(f"""# Generated by infra/terraform/azure/scripts/helm-values.sh
azure:
  storageAccountName: {o["storage_account_name"]}
objectStore:
  url: {o["object_store_url"]}
serviceAccount:
  clientId: {ids["gateway"]}
dashboard:
  serviceAccount:
    clientId: {ids["dashboard"]}
operator:
  serviceAccount:
    clientId: {ids["operator"]}
workerIdentity:
  clientId: {ids["worker"]}""")
PY
